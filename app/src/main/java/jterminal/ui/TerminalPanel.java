    public void processKeyDown(KeyEvent evt) {
        this.last = System.currentTimeMillis();
        if (skipChar(evt) == true) {
            return;
        }

        boolean add = true;
        if (evt.getKeyCode() == 8) {
            add = false;
            this.getManager().trimInput();
        }

        if (evt.getKeyCode() == 16) {
            add = false;

        }

        if (evt.getKeyCode() == 17) {
            add = false;

        }

        if (evt.getKeyCode() == 10) {
            add = false;
            this.processInput();
        }

        if (evt.getKeyCode() == 37) {
            add = false;
            this.getManager().decrementInputCursor();

        }

        if (evt.getKeyCode() == 39) {
            add = false;
            this.getManager().incrementInputCursor();

        }

        if (evt.getKeyCode() == 38) {
            add = false;

            this.getManager().incrementIndex(evt.isShiftDown());

        }

        if (evt.getKeyCode() == 40) {
            add = false;
            this.getManager().decrementIndex(evt.isShiftDown());

        }

        if (add == true) {
            this.getManager().appendInput(evt.getKeyChar() + "");
        }
        // this.display.repaint();
        this.repaint();
    }

    private boolean skipChar(KeyEvent evt) {
        if (evt.getKeyChar() == KeyEvent.SHIFT_DOWN_MASK) {
            return true;
        }

        if (evt.getKeyCode() == 20) {
            return true;
        }

        return false;
    }

    private void processInput() {
        String input = this.getManager().getInput();
        this.getCommander().processInput(input);
    }

    private void clear() {
        this.getManager().clearOutput();
        this.repaint();
    }

