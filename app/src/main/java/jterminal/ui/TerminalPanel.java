    private void updateManager() {
        if (this.getManager() == null) {
            this.manager = new JTerminalManager(250, this.getRowCount(), this.getColCount());
        } else {
            this.getManager().updateDimensions(this.getRowCount(), this.getColCount());
        }

    }

    private int getColCount() {
        double value = (this.width - this.getPadding() * 2) / 8;
        return (int) (value);
    }

    private int getRowCount() {
        double ret = (this.height - this.getPadding() * 5) / this.rowHeight();

        return (int) (ret);
    }

    private JTerminalManager getManager() {
        return this.manager;
    }

    @Override
    public void paint(Graphics g) {

        super.paint(g);
        this.fillDisplay(g);
        this.setupForText(g);
        this.printInput(g);
        this.printOutput(g);

    }

    private void printOutput(Graphics g) {
        List<String> out = this.getCommander().getOutput();
        int row = 0;

        for (String line : out) {
            this.printLine(g, line, row);

            row++;
        }

    }

