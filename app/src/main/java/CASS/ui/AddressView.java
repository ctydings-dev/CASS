    private void loadData() throws ServiceError {
        this.addresses = this.getManager().getFullAddress();
        this.setData(this.addresses);
    }

    private void setData(List<CompositeAddress> toSet) {
        Object[] data = new Object[toSet.size()];
        for (int index = 0; index < data.length; index++) {
            data[index] = toSet.get(index);
        }
        TableModel toUse = new AddressTableModel(data);
        this.addressTable.setModel(toUse);
    }

    private void filter() {

        List<CompositeAddress> toUse = DataObjectGenerator.createList();

        String street = this.stateFilter.getText().trim().toUpperCase();
        String town = this.townFilter.getText().trim().toUpperCase();
        String zip = this.zipFilter.getText().trim().toUpperCase();
        String state = this.stateFilter.getText().trim().toUpperCase();
        String country = this.countryFilter.getText().trim().toUpperCase();
        if (street.length() < 1) {
            if (town.length() < 1) {
                if (zip.length() < 1) {
                    if (state.length() < 1) {
                        if (country.length() < 1) {
                            this.setData(this.addresses);
                            return;
                        }
                    }
                }
            }
        }

        for (CompositeAddress addr : this.addresses) {
            boolean add = true;
            if (add == true) {
                if (street.length() > 0) {
                    if (!addr.getAddress().getStreet().toUpperCase().contains(street)) {

                        if (!addr.getAddress().getStreet2().toUpperCase().contains(street)) {
                            add = false;
                        }
                    }
                }
            }
            if (add == true) {
                if (town.length() > 0) {
                    if (!addr.getCity().getCityName().toUpperCase().contains(town)) {
                        add = false;
                    }
                }
            }
            if (add == true) {
                if (zip.length() > 0) {
                    if (!addr.getAddress().getPostCode().toUpperCase().contains(zip)) {
                        add = false;
                    }
                }
            }
            if (add == true) {
                if (state.length() > 0) {
                    if (!addr.getState().getAbbreviation().toUpperCase().contains(state)) {
                        if (!addr.getState().getStateName().toUpperCase().contains(state)) {
                            add = false;
                        }
                    }
                }
            }
            if (add == true) {
                if (country.length() > 0) {

                    if (!addr.getCountry().getCountryName().toUpperCase().contains(country)) {
                        if (!addr.getCountry().getCountryName().toUpperCase().contains(country)) {
                            add = false;
                        }
                    }
                }
            }

            if (add == true) {
                toUse.add(addr);
            }
        }
        this.setData(toUse);
    }

