    private void setAddress(int key) {
        this.streetDisplay.setText("");
        this.zipDisplay.setText("");
        this.townDisplay.setText("");
        this.stateDisplay.setText("");
        this.counrtyDisplay.setText("");
        if (key < 0) {
            return;
        }
        for (CompositeAddress adr : this.addresses) {
            if (adr.getAddress().getKey() == key) {
                this.streetDisplay.setText(adr.getAddress().getStreet() + " " + adr.getAddress().getStreet2());
                this.zipDisplay.setText((adr.getAddress().getPostCode()));
                this.townDisplay.setText(adr.getCity().getCityName());
                this.stateDisplay.setText(adr.getState().getStateName());
                this.counrtyDisplay.setText(adr.getCountry().getCountryName());
                return;
            }

        }
    }

    private void addressTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_addressTableMouseClicked
        int row = this.addressTable.getSelectedRow();
        AddressTableModel model = (AddressTableModel) this.addressTable.getModel();
        int key = (int) model.getValueAt(row, -1);
        setAddress(key);

        try {
            List<PersonDTO> people = this.getCaller().getPersonManager().getPeopleByAddress(key);
            PersonTableModel peopleModel = new PersonTableModel(people.toArray(), true);
            this.personTable.setModel(peopleModel);

        } catch (ServiceError ex) {
            this.getCaller().displayError(ex);
        }

    }//GEN-LAST:event_addressTableMouseClicked

